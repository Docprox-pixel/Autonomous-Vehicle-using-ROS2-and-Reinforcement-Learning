#!/usr/bin/env python3
"""Write the ego-car sensor suite from config/sensor_layout.yaml into a Webots world.

Keeps worlds and the bridge in sync (one source of truth) and lets us fit the same car to
any world (city.wbt, city_traffic.wbt, ...).

  python3 tools/install_sensors.py worlds/city.wbt                    # in place
  python3 tools/install_sensors.py IN.wbt --out worlds/city_traffic.wbt --def WEBOTS_VEHICLE0

The ego car is the node 'DEF <def> BmwX5 { ... }' (default DEF vehicle). It keeps its DEF name,
gets name "vehicle" (what the bridge connects to) and controller <extern>. In SUMO worlds use
--def WEBOTS_VEHICLE0: SumoInterface adds WEBOTS_VEHICLE<n> cars to the traffic simulation, so
the SUMO cars see and react to the ego car. With --pick-car N the N-th BmwX5 is used instead.
"""
import argparse
import math
import os
import re

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))

ROOF_MOUNT_Z = 0.5   # SENSOR_MOUNT height above the BmwX5 sensorsSlotTop (1.0, 0, 1.45)
SLOT_TOP = (1.0, 0.0, 1.45)


def find_block(text, start):
    """Return the index just after the '}' that closes the '{' at/after `start`."""
    i = text.index('{', start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return j + 1
    raise ValueError('unbalanced braces')


def field(block, name, default):
    m = re.search(rf'^\s*{name}\s+([^\n]+)$', block, re.M)
    return m.group(1).strip() if m else default


def lidar_node(l, indent):
    p = indent
    lines = [
        f'{p}Lidar {{',
        f'{p}  name "{l["name"]}"',
        f'{p}  horizontalResolution {l["resolution"]}',
        f'{p}  fieldOfView {l["hfov"]}',
        f'{p}  verticalFieldOfView {l["vfov"]}',
        f'{p}  numberOfLayers {l["layers"]}',
        f'{p}  minRange {l["range"][0]}',
        f'{p}  maxRange {l["range"][1]}',
        f'{p}}}',
    ]
    return '\n'.join(lines)


def build_vehicle(layout, translation, rotation, def_name='vehicle'):
    lidars = {l['name']: l for l in layout['lidars']}
    roof = lidars.pop('lidar')
    expect = (SLOT_TOP[0], SLOT_TOP[1], SLOT_TOP[2] + ROOF_MOUNT_Z)
    if any(abs(a - b) > 1e-6 for a, b in zip(roof['xyz'], expect)):
        raise SystemExit(f'roof lidar xyz {roof["xyz"]} must equal sensorsSlotTop + mount = {expect}')

    corners = []
    for l in lidars.values():
        x, y, z = l['xyz']
        corners.append('\n'.join([
            '    Pose {',
            f'      translation {x} {y} {z}',
            f'      rotation 0 0 1 {l["yaw"]}',
            '      children [',
            lidar_node(l, '        '),
            '      ]',
            '    }',
        ]))

    surround = '\n'.join('\n'.join([
        '        Pose {',
        f'          translation {c["xyz"][0]} {c["xyz"][1]} {c["xyz"][2]}',
        f'          rotation 0 0 1 {c["yaw"]}',
        '          children [',
        '            Camera {',
        f'              name "{c["name"]}"',
        f'              width {c["width"]}',
        f'              height {c["height"]}',
        f'              fieldOfView {c["fov"]}',
        '            }',
        '          ]',
        '        }']) for c in layout.get('surround_cameras', []))
    return f'''DEF {def_name} BmwX5 {{
  translation {translation}
  rotation {rotation}
  name "vehicle"
  controller "<extern>"
  # ---- generated by tools/install_sensors.py from config/sensor_layout.yaml: do not hand-edit ----
  sensorsSlotTop [
    # Pose (not Solid): the IMU/gyro/accelerometer then belong to the car body, which has physics.
    DEF SENSOR_MOUNT Pose {{
      translation 0 0 {ROOF_MOUNT_Z}
      children [
        Camera {{
          name "front_camera"
          width 640
          height 480
          fieldOfView 1.2
        }}
{surround}
{lidar_node(roof, '        ')}
        GPS {{
          name "gps"
        }}
        InertialUnit {{
          name "imu"
        }}
        Gyro {{
          name "gyro"
        }}
        Accelerometer {{
          name "accelerometer"
        }}
      ]
    }}
  ]
  # Corner (near-field) lidars, poses in the car frame (sensorsSlotCenter = car origin).
  sensorsSlotCenter [
{chr(10).join(corners)}
  ]
}}'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('world')
    ap.add_argument('--out')
    ap.add_argument('--layout', default=os.path.join(HERE, '..', 'config', 'sensor_layout.yaml'))
    ap.add_argument('--def', dest='def_name', default='vehicle', help='DEF name of the ego BmwX5')
    ap.add_argument('--pick-car', type=int, default=None, help='use the N-th BmwX5 as the ego car')
    a = ap.parse_args()

    text = open(a.world).read()
    layout = yaml.safe_load(open(a.layout))

    if a.pick_car is None:
        m = re.search(rf'DEF {re.escape(a.def_name)} BmwX5\s*\{{', text)
        if not m:
            raise SystemExit(f"no 'DEF {a.def_name} BmwX5' in world; use --def or --pick-car N")
        start = m.start()
    else:
        starts = [m.start() for m in re.finditer(r'(?m)^(?:DEF \S+ )?BmwX5\s*\{', text)]
        if a.pick_car >= len(starts):
            raise SystemExit(f'only {len(starts)} BmwX5 in world')
        start = starts[a.pick_car]
    end = find_block(text, start)
    old = text[start:end]
    new = build_vehicle(layout, field(old, 'translation', '0 0 0.4'), field(old, 'rotation', '0 0 1 0'),
                        a.def_name)
    text = text[:start] + new + text[end:]

    open(a.out or a.world, 'w').write(text)
    print(f'ego car with {len(layout["lidars"])} lidars written to {a.out or a.world}')


if __name__ == '__main__':
    main()
